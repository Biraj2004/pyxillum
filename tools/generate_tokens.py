#!/usr/bin/env python3
"""
Pyxillum Design Token Generator.
Reads `design/tokens.json` and generates native token files:
- apps/windows/Pyxillum/Themes/Tokens.xaml (WinUI 3 ResourceDictionary)
- apps/macos/PyxillumCore/Sources/Tokens.swift (SwiftUI constants)
- apps/linux/data/tokens.css (GTK4 CSS variables)
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS_PATH = ROOT / "design" / "tokens.json"

def hex_to_winui_color(hex_str: str) -> str:
    hex_clean = hex_str.lstrip("#")
    if len(hex_clean) == 6:
        return f"#FF{hex_clean.upper()}"
    return f"#{hex_clean.upper()}"

def main():
    with open(TOKENS_PATH, "r", encoding="utf-8") as f:
        tokens = json.load(f)

    # 1. Generate WinUI 3 Tokens.xaml
    winui_dir = ROOT / "apps" / "windows" / "Pyxillum" / "Themes"
    winui_dir.mkdir(parents=True, exist_ok=True)
    winui_path = winui_dir / "Tokens.xaml"

    xaml_lines = [
        '<ResourceDictionary',
        '    xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
        '    <!-- Spatial Spacing Tokens -->',
    ]
    for key, val in tokens.get("spacing", {}).items():
        pascal_key = "".join(part.capitalize() for part in key.split("_"))
        xaml_lines.append(f'    <x:Double x:Key="{pascal_key}">{val}</x:Double>')
        xaml_lines.append(f'    <Thickness x:Key="{pascal_key}Thickness">{val},{val},{val},{val}</Thickness>')

    xaml_lines.append('    <!-- Corner Radii Tokens -->')
    for key, val in tokens.get("radii", {}).items():
        pascal_key = "".join(part.capitalize() for part in key.split("_"))
        xaml_lines.append(f'    <CornerRadius x:Key="Radius{pascal_key}">{val}</CornerRadius>')

    xaml_lines.append('    <!-- Semantic Colors -->')
    for key, color_info in tokens.get("semantic_colors", {}).items():
        if not isinstance(color_info, dict):
            continue
        hex_val = color_info.get("hex_fallback", "#000000")
        argb = hex_to_winui_color(hex_val)
        pascal_key = "".join(part.capitalize() for part in key.split("_"))
        xaml_lines.append(f'    <Color x:Key="Color{pascal_key}">{argb}</Color>')
        xaml_lines.append(f'    <SolidColorBrush x:Key="Brush{pascal_key}" Color="{{StaticResource Color{pascal_key}}}" />')

    xaml_lines.append('</ResourceDictionary>')
    xaml_content = "\n".join(xaml_lines) + "\n"
    winui_path.write_text(xaml_content, encoding="utf-8")
    print(f"Generated: {winui_path}")

    # 2. Generate SwiftUI Tokens.swift
    macos_dir = ROOT / "apps" / "macos" / "PyxillumCore" / "Sources"
    macos_dir.mkdir(parents=True, exist_ok=True)
    swift_path = macos_dir / "Tokens.swift"

    swift_lines = [
        '// Generated by tools/generate_tokens.py - DO NOT EDIT MANUALLY',
        'import SwiftUI',
        '',
        'public enum SpacingTokens {',
    ]
    for key, val in tokens.get("spacing", {}).items():
        camel_key = key.split("_")[0] + "".join(part.capitalize() for part in key.split("_")[1:])
        swift_lines.append(f'    public static let {camel_key}: CGFloat = {val}.0')
    swift_lines.append('}')
    swift_lines.append('')
    swift_lines.append('public enum RadiiTokens {')
    for key, val in tokens.get("radii", {}).items():
        camel_key = key.split("_")[0] + "".join(part.capitalize() for part in key.split("_")[1:])
        swift_lines.append(f'    public static let {camel_key}: CGFloat = {val}.0')
    swift_lines.append('}')
    swift_lines.append('')
    swift_lines.append('public enum SemanticColors {')
    for key, color_info in tokens.get("semantic_colors", {}).items():
        if not isinstance(color_info, dict):
            continue
        hex_val = color_info.get("hex_fallback", "#000000")
        camel_key = key.split("_")[0] + "".join(part.capitalize() for part in key.split("_")[1:])
        swift_lines.append(f'    public static let {camel_key}Hex = "{hex_val}"')
    swift_lines.append('}')
    swift_content = "\n".join(swift_lines) + "\n"
    swift_path.write_text(swift_content, encoding="utf-8")
    print(f"Generated: {swift_path}")

    # 3. Generate Linux GTK CSS tokens.css
    linux_dir = ROOT / "apps" / "linux" / "data"
    linux_dir.mkdir(parents=True, exist_ok=True)
    css_path = linux_dir / "tokens.css"

    css_lines = [
        '/* Generated by tools/generate_tokens.py - DO NOT EDIT MANUALLY */',
        ':root {',
    ]
    for key, val in tokens.get("spacing", {}).items():
        css_key = key.replace("_", "-")
        css_lines.append(f'    --pyx-spacing-{css_key}: {val}px;')
    for key, val in tokens.get("radii", {}).items():
        css_key = key.replace("_", "-")
        css_lines.append(f'    --pyx-radius-{css_key}: {val}px;')
    for key, color_info in tokens.get("semantic_colors", {}).items():
        if not isinstance(color_info, dict):
            continue
        hex_val = color_info.get("hex_fallback", "#000000")
        css_key = key.replace("_", "-")
        css_lines.append(f'    --pyx-color-{css_key}: {hex_val};')
    css_lines.append('}')
    css_content = "\n".join(css_lines) + "\n"
    css_path.write_text(css_content, encoding="utf-8")
    print(f"Generated: {css_path}")

if __name__ == "__main__":
    main()
